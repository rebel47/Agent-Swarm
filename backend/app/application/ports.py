from __future__ import annotations

from typing import Protocol

from ..domain.investigations import ReviewBrief


class InvestigationRepository(Protocol):
    async def create(self, brief: ReviewBrief, owner: str, key: str | None) -> str: ...
    async def get(self, job_id: str, owner: str) -> dict: ...
    async def list(self, owner: str, offset: int, limit: int) -> dict: ...
    async def cancel(self, job_id: str, owner: str) -> None: ...
    async def steps(self, job_id: str, agent_id: str, offset: int, limit: int) -> dict: ...
    async def patches(self, job_id: str, offset: int, limit: int) -> dict: ...
    async def events(self, job_id: str, after: int, limit: int, latest: bool) -> list[dict]: ...


class WakeupQueue(Protocol):
    async def wake(self, job_id: str) -> None: ...


class SourceRepository(Protocol):
    async def list(self, owner: str) -> list[dict]: ...
    async def admit(self, location: str, ref: str | None, owner: str) -> dict: ...
    async def finish(self, source_id: str, info=None, error=None) -> dict: ...
    async def remove(self, source_id: str, owner: str) -> None: ...


class SourcePreparer(Protocol):
    async def prepare(self, record: dict) -> dict: ...
